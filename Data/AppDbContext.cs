// Họ và tên: Lại Anh Quân
// Mã sinh viên: 23103100255
// Nội dung thực hiện: Xây dựng appDbContext, cấu hình các entity, quan hệ, ràng buộc, index, và cách lưu trữ enum trong cơ sở dữ liệu.

using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;
using QuanLyThuVien_UNETI4_TI17A1CL.Models;
using QuanLyThuVien_UNETI4_TI17A1CL.Models.Enums;

namespace QuanLyThuVien_UNETI4_TI17A1CL.Data;

public class AppDbContext : DbContext
{
    public AppDbContext(DbContextOptions<AppDbContext> options) : base(options) { }

    public DbSet<TaiKhoan> TaiKhoans => Set<TaiKhoan>();
    public DbSet<BanDoc> BanDocs => Set<BanDoc>();
    public DbSet<TheLoai> TheLoais => Set<TheLoai>();
    public DbSet<Sach> Sachs => Set<Sach>();
    public DbSet<PhieuMuon> PhieuMuons => Set<PhieuMuon>();
    public DbSet<GiaHanMuon> GiaHanMuons => Set<GiaHanMuon>();
    public DbSet<TraSach> TraSachs => Set<TraSach>();
    public DbSet<CauHinhThuVien> CauHinhThuViens => Set<CauHinhThuVien>();
    public DbSet<PhieuMuonLichSu> PhieuMuonLichSus => Set<PhieuMuonLichSu>();
    public DbSet<Otp> Otps => Set<Otp>();

    // Enums are stored as strings holding the member name, so the filters below compare against those names.
    private static readonly string ActiveLoanFilter =
        $"[TrangThai] IN (N'{nameof(TrangThaiPhieuMuon.ChoDuyet)}', N'{nameof(TrangThaiPhieuMuon.DaDuyet)}', N'{nameof(TrangThaiPhieuMuon.DangMuon)}')";

    private static readonly string PendingExtensionFilter =
        $"[TrangThai] = N'{nameof(TrangThaiGiaHan.ChoDuyet)}'";

    protected override void OnModelCreating(ModelBuilder b)
    {
        base.OnModelCreating(b);

        // ---- Unique rules ----
        b.Entity<TaiKhoan>().HasIndex(x => x.TenDangNhap).IsUnique();
        b.Entity<TheLoai>().HasIndex(x => x.TenTheLoai).IsUnique();

        // ---- BanDoc.MaSoThe: generated by a SQL Server SEQUENCE (TV-000001, TV-000002, ...) ----
        b.HasSequence<int>("SoTheSeq").StartsAt(1).IncrementsBy(1);
        b.Entity<BanDoc>().Property(x => x.MaSoThe)
            .IsRequired()
            .HasMaxLength(50)
            .HasDefaultValueSql("'TV-' + RIGHT('000000' + CAST(NEXT VALUE FOR SoTheSeq AS varchar(10)), 6)");
        b.Entity<BanDoc>().HasIndex(x => x.MaSoThe).IsUnique();

        // ---- Relationships ----
        // TaiKhoan 1 - 0..1 BanDoc (unique index on BanDoc.MaTaiKhoan comes from the one-to-one)
        b.Entity<BanDoc>()
            .HasOne(x => x.TaiKhoan).WithOne(x => x.BanDoc)
            .HasForeignKey<BanDoc>(x => x.MaTaiKhoan);

        // PhieuMuon 1 - 0..1 TraSach (unique index on TraSach.MaPhieuMuon comes from the one-to-one)
        b.Entity<TraSach>()
            .HasOne(x => x.PhieuMuon).WithOne(x => x.TraSach)
            .HasForeignKey<TraSach>(x => x.MaPhieuMuon);

        // Staff references
        b.Entity<TraSach>()
            .HasOne(x => x.NguoiNhan).WithMany().HasForeignKey(x => x.MaNguoiNhan);
        b.Entity<PhieuMuonLichSu>()
            .HasOne(x => x.NguoiThucHien).WithMany().HasForeignKey(x => x.MaNguoiThucHien);

        // ---- Money / ratio precision ----
        b.Entity<Sach>().Property(x => x.GiaBia).HasPrecision(18, 2);
        b.Entity<Sach>().Property(x => x.RowVersion).IsRowVersion();
        b.Entity<TraSach>().Property(x => x.TienPhat).HasPrecision(18, 2);
        b.Entity<CauHinhThuVien>().Property(x => x.TienPhatMoiNgay).HasPrecision(18, 2);
        b.Entity<CauHinhThuVien>().Property(x => x.TyLePhatHuHong).HasPrecision(5, 2);
        b.Entity<CauHinhThuVien>().Property(x => x.TyLePhatMat).HasPrecision(5, 2);

        // ---- Integrity: filtered unique indexes ----
        // One active loan per reader per book
        b.Entity<PhieuMuon>()
            .HasIndex(x => new { x.MaBanDoc, x.MaSach })
            .IsUnique()
            .HasFilter(ActiveLoanFilter)
            .HasDatabaseName("UX_PhieuMuon_BanDoc_Sach_DangXuLy");

        // One pending extension request per loan
        b.Entity<GiaHanMuon>()
            .HasIndex(x => x.MaPhieuMuon)
            .IsUnique()
            .HasFilter(PendingExtensionFilter)
            .HasDatabaseName("UX_GiaHanMuon_ChoDuyet");

        // ---- Integrity: CHECK constraints ----
        b.Entity<Sach>().ToTable(t =>
        {
            t.HasCheckConstraint("CK_Sach_SoLuongTong", "[SoLuongTong] >= 0");
            t.HasCheckConstraint("CK_Sach_GiaBia", "[GiaBia] >= 0");
            t.HasCheckConstraint("CK_Sach_NamXuatBan", "[NamXuatBan] >= 1450");
        });
        b.Entity<BanDoc>().ToTable(t =>
            t.HasCheckConstraint("CK_BanDoc_HanThe", "[NgayHetHanThe] > [NgayCapThe]"));
        b.Entity<GiaHanMuon>().ToTable(t =>
            t.HasCheckConstraint("CK_GiaHanMuon_HanTra", "[HanTraMoi] > [HanTraCu]"));
        b.Entity<TraSach>().ToTable(t =>
        {
            t.HasCheckConstraint("CK_TraSach_SoNgayTre", "[SoNgayTre] >= 0");
            t.HasCheckConstraint("CK_TraSach_TienPhat", "[TienPhat] >= 0");
        });
        b.Entity<CauHinhThuVien>().ToTable(t =>
            t.HasCheckConstraint("CK_CauHinhThuVien_MotDong", "[MaCauHinh] = 1"));

        // ---- Indexes for list / statistics queries ----
        b.Entity<PhieuMuon>().HasIndex(x => new { x.MaSach, x.TrangThai });
        b.Entity<PhieuMuon>().HasIndex(x => new { x.MaBanDoc, x.TrangThai });
        b.Entity<Sach>().HasIndex(x => x.TrangThai);
        b.Entity<Sach>().HasIndex(x => x.TenSach);

        // ---- Enums -> string columns (nvarchar(50)), nullable enums included ----
        foreach (var property in b.Model.GetEntityTypes().SelectMany(e => e.GetProperties()))
        {
            var type = Nullable.GetUnderlyingType(property.ClrType) ?? property.ClrType;
            if (!type.IsEnum) continue;

            var converter = (ValueConverter)Activator.CreateInstance(
                typeof(EnumToStringConverter<>).MakeGenericType(type))!;
            property.SetValueConverter(converter);
            property.SetMaxLength(50);
        }

        // ---- Never cascade-delete (keeps history, avoids SQL Server multiple-cascade-path errors) ----
        foreach (var fk in b.Model.GetEntityTypes().SelectMany(e => e.GetForeignKeys()))
            fk.DeleteBehavior = DeleteBehavior.Restrict;
    }
}
